  await prisma.session.update({where:{id:seller.id},data:{revokedAt:null}})
  await prisma.user.update({where:{id:user.id},data:{status:'INACTIVE'}})
  await probe('inactive user',request())
  await prisma.user.update({where:{id:user.id},data:{status:'SUSPENDED'}})
  await probe('suspended user',request())
  await prisma.user.update({where:{id:user.id},data:{status:'ACTIVE',lockedUntil:new Date(Date.now()+60000)}})
  await probe('locked PIN',request(),429)
  await prisma.user.update({where:{id:user.id},data:{lockedUntil:null,accessSchedule:{timezone:'UTC',windows:[]}}})
  await probe('outside access schedule',request())
  check((await prisma.session.findUniqueOrThrow({where:{id:seller.id}})).revokedAt!==null,'outside schedule revokes credential exactly as requireSession')
  await prisma.session.update({where:{id:seller.id},data:{revokedAt:null}})
  await prisma.user.update({where:{id:user.id},data:{accessSchedule:require('@prisma/client').Prisma.JsonNull}})
  await prisma.branch.update({where:{id:branch.id},data:{isActive:false}})
  await probe('inactive branch',request())
  await prisma.branch.update({where:{id:branch.id},data:{isActive:true}})
  await prisma.user.update({where:{id:user.id},data:{branchId:otherBranch.id}})
  const beforeMismatch=await prisma.session.findUniqueOrThrow({where:{id:seller.id}})
  await probe('assigned branch no longer matches session',request())
  check((await prisma.session.findUniqueOrThrow({where:{id:seller.id}})).lastSeenAt.getTime()===beforeMismatch.lastSeenAt.getTime(),'branch mismatch never updates session')
  await prisma.user.update({where:{id:user.id},data:{branchId:branch.id}})
