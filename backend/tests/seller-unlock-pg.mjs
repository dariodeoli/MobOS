  await probe('wrong PIN',request(cookie,{pin:'1111'}),422,'INVALID_PIN')
  await probe('correct retry',request(),200)
  await probe('target substitution rejected',request(cookie,{pin:'2874',sellerId:'other'}),400)
  await probe('tenant substitution rejected',request(cookie,{pin:'2874',tenantId:'other'}),400)
  await probe('foreign browser origin',request(cookie,{pin:'2874'},'https://hostile.example.test'))
  await probe('no cookie',request(''))
